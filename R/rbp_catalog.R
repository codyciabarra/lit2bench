#' The eCLIP peak sets available for one protein.
#'
#' @param rbp gene symbol, e.g. "TARDBP", "PTBP1", "RBFOX2". Case-insensitive.
#' @return list of dataset descriptors in the shape clip_peaks.R consumes, or
#'         an empty list when ENCODE has no eCLIP for this protein. An empty
#'         list is a real answer -- "not measured" -- and callers must render it
#'         as such rather than as absence of binding.
clip_datasets_for <- function(rbp) {
  if (is.null(rbp) || !nzchar(rbp)) return(list())
  tbl <- .rbp_catalog()
  hit <- tbl[tbl$rbp == toupper(rbp), , drop = FALSE]
  if (nrow(hit) == 0) return(list())
  lapply(seq_len(nrow(hit)), function(i) list(
    id = sprintf("%s_%s_%s", tolower(hit$rbp[i]), tolower(gsub("[^A-Za-z0-9]", "", hit$cell[i])), hit$file[i]),
    rbp = hit$rbp[i], cell = hit$cell[i], experiment = hit$experiment[i],
    file = hit$file[i], assembly = "hg38", kind = "reproducible (2 biological replicates)"))
}

#' Join a character vector for prose: "a", "a and b", "a, b and c".
#' Lives here because all three of rbp_catalog / rbp_motifs / clip_peaks build
#' sentences from lists of cells or datasets, and " and " between three items
#' reads as a mistake. Two proteins (DGCR8, HNRNPU) have three cell types.
.rbp_and_list <- function(x) {
  n <- length(x)
  if (n <= 1L) return(paste(x, collapse = ""))
  if (n == 2L) return(paste(x, collapse = " and "))
  paste0(paste(x[-n], collapse = ", "), " and ", x[n])
}

#' Every protein with an eCLIP peak set, alphabetically.
clip_rbps <- function() sort(unique(.rbp_catalog()$rbp))

#' Does ENCODE have eCLIP for this protein?
clip_has_rbp <- function(rbp) !is.null(rbp) && nzchar(rbp) && toupper(rbp) %in% .rbp_catalog()$rbp

.rbp_catalog_env <- new.env(parent = emptyenv())

.rbp_catalog <- function() {
  hit <- .rbp_catalog_env$tbl
  if (!is.null(hit)) return(hit)
  parts <- strsplit(strsplit(.RBP_CATALOG_RAW, "\n", fixed = TRUE)[[1]], " ", fixed = TRUE)
  parts <- Filter(function(p) length(p) == 4L, parts)
  tbl <- data.frame(
    rbp        = vapply(parts, `[`, character(1), 1L),
    experiment = vapply(parts, `[`, character(1), 2L),
    file       = vapply(parts, `[`, character(1), 3L),
    cell       = unname(.RBP_CELL_NAMES[vapply(parts, `[`, character(1), 4L)]),
    stringsAsFactors = FALSE)
  assign("tbl", tbl, envir = .rbp_catalog_env)
  tbl
}

#' Re-derive the catalogue from ENCODE. Not called at runtime -- see the header.
#'
#' Prints the block that belongs in .RBP_CATALOG_RAW. Targeted regex, no JSON
#' package, the same rule fetch_genomic() follows.
.rbp_catalog_refresh <- function(timeout_s = 180) {
  url_str <- paste0("https://www.encodeproject.org/search/?type=File&assay_term_name=eCLIP",
                    "&file_format=bed&assembly=GRCh38&status=released&format=json&limit=all",
                    "&field=accession&field=target.label&field=biosample_ontology.term_name",
                    "&field=dataset&field=biological_replicates&field=analysis_step_version")
  txt <- tryCatch({
    old <- getOption("timeout"); options(timeout = timeout_s)
    on.exit(options(timeout = old), add = TRUE)
    con <- url(url_str); on.exit(try(close(con), silent = TRUE), add = TRUE)
    paste(readLines(con, warn = FALSE), collapse = "")
  }, error = function(e) NULL)
  if (is.null(txt)) { message("ENCODE unreachable."); return(invisible(NULL)) }
  # One record per file; split on the accession key so each chunk is self-contained.
  chunks <- strsplit(txt, '{"accession"', fixed = TRUE)[[1]][-1]
  keep <- character(0)
  for (ch in chunks) {
    if (!grepl("merge-peaks", ch, fixed = TRUE)) next
    reps <- regmatches(ch, regexpr('"biological_replicates":\\[[^]]*\\]', ch))
    if (!length(reps) || length(gregexpr("[0-9]+", reps)[[1]]) < 2) next
    acc  <- regmatches(ch, regexpr("ENCFF[0-9A-Z]+", ch))
    expt <- regmatches(ch, regexpr("ENCSR[0-9A-Z]+", ch))
    lab  <- regmatches(ch, regexpr('"label":"[^"]+"', ch))
    cell <- regmatches(ch, regexpr('"term_name":"[^"]+"', ch))
    if (!length(acc) || !length(expt) || !length(lab) || !length(cell)) next
    lab  <- sub('"label":"', "", sub('"$', "", lab), fixed = TRUE)
    cell <- sub('"term_name":"', "", sub('"$', "", cell), fixed = TRUE)
    code <- names(.RBP_CELL_NAMES)[match(cell, .RBP_CELL_NAMES)]
    if (is.na(code)) next
    keep <- c(keep, sprintf("%s %s %s %s", lab, expt, acc, code))
  }
  keep <- sort(unique(keep))
  message(sprintf("%d reproducible peak files, %d proteins.", length(keep),
                  length(unique(sub(" .*", "", keep)))))
  cat(paste(keep, collapse = "\n"), "\n")
  invisible(keep)
}
