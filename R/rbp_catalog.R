# rbp_catalog.R -- which published eCLIP experiment answers for which protein.
#
# 168 RNA-binding proteins, 252 peak files, every one of them ENCODE's
# REPRODUCIBLE peak set: the merge-peaks output computed across two biological
# replicates. That qualifier is the whole point of this file existing rather
# than a search at runtime, and it is worth being explicit about why.
#
# ENCODE marks one file per experiment `preferred_default`. It is tempting to
# select on that, and it is wrong here. Measured against the released eCLIP set:
# 252 files carry preferred_default and 252 files are reproducible merged peaks,
# but only 27 files are BOTH. The other 225 preferred_default files come from
# the normalization step on a SINGLE biological replicate -- for TARDBP in K562
# that is 107,504 peaks against the reproducible set's 7,010, a 15x looser
# answer with no cross-replicate support. Selecting on preferred_default would
# have produced a catalogue of exactly the right shape -- 168 targets, 252
# files, one to three per target -- made of the wrong files, and reported far
# more proteins as "bound" than the data supports.
#
# So the selector is: analysis step contains `merge-peaks`, and
# `biological_replicates` has at least two entries. Both ENCODE3
# (eclip-merge-peaks-step-v-1-0) and ENCODE4 (encode4-...) generations qualify.
#
# Pinned by accession, not discovered at runtime, for the reasons clip_peaks.R
# already gives: an accession is permanent, a search ranking is not, and the
# common path should be one download rather than a search plus a download. The
# three TARDBP files this app shipped with are all present here unchanged, so
# generalising to 168 proteins moved no TDP-43 answer.
#
# Regenerate with .rbp_catalog_refresh() (below) when ENCODE releases more.
# Cells: K = K562, H = HepG2, A = adrenal gland.

